"""
rec.lua 写入模块

将识别结果写入本地 lua 脚本文件，供 GHUB Lua 压枪宏通过 dofile 读取。
使用原子写入（先写临时文件再 rename）避免读写竞争。

@author hqzqaq
@since 2026-06-25
@version 1.0
"""

import logging
import os
from pathlib import Path

logger = logging.getLogger(__name__)

_DEFAULT_REC_PATH = str(Path(__file__).resolve().parent.parent.parent / "pubg_rec.lua")


class RecLuaWriter:
    """将识别结果写入 rec.lua 文件"""

    def __init__(self, path: str | None = None) -> None:
        self.path: str = path or _DEFAULT_REC_PATH

    def write(
        self,
        gun: str = "",
        muzzle: int = 1,
        grip: int = 1,
        stock: int = 1,
        scope: int = 1,
    ) -> None:
        """原子写入 rec.lua

        Args:
            gun: 枪械名称，如 "M416"，空字符串表示未识别
            muzzle: 枪口索引 (1=无, 2=补偿器, 3=消焰器, 4=消音器, 5=制退器)
            grip: 握把索引 (1=无, 2=垂直, 3=斜向, 4=拇指, 5=半截, 6=轻型)
            stock: 枪托索引 (1=无, 2=战术, 3=重型)
            scope: 倍镜 (1=红点/全息, 2=2倍, 3=3倍, 4=4倍, 6=6倍)
        """
        content = (
            "-- auto-generated by pubg-gun-control, do not edit\n"
            f'rec_gun = "{gun}"\n'
            f"rec_muzzle = {muzzle}\n"
            f"rec_grip = {grip}\n"
            f"rec_stock = {stock}\n"
            f"rec_scope = {scope}\n"
        )

        tmp_path = self.path + ".tmp"
        try:
            with open(tmp_path, "w", encoding="utf-8") as f:
                f.write(content)
            os.replace(tmp_path, self.path)
            logger.debug("rec.lua 已写入: gun=%s", gun)
        except OSError as exc:
            logger.error("写入 rec.lua 失败: %s", exc)

    def get_path(self) -> str:
        """返回 rec.lua 的绝对路径"""
        return str(Path(self.path).resolve())
