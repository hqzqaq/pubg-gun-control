"""
rec.lua 写入模块

将识别结果写入本地 lua 脚本文件，供 GHUB Lua 压枪宏通过 dofile 读取。
使用原子写入（先写临时文件再 rename）避免读写竞争。

@author hqzqaq
@since 2026-06-25
@version 1.0
"""

import logging
import os
import sys
import threading
from pathlib import Path

logger = logging.getLogger(__name__)


def _get_project_root() -> Path:
    if getattr(sys, "frozen", False) and hasattr(sys, "_MEIPASS"):
        return Path(sys._MEIPASS)
    return Path(__file__).resolve().parent.parent.parent


_DEFAULT_REC_PATH = str(_get_project_root() / "pubg_rec.lua")


class RecLuaWriter:
    """将识别结果写入 rec.lua 文件

    内部保存最近一次的完整状态：姿态与枪械/配件来自不同的更新源，
    更新其中一项时必须沿用其他项的旧值，否则会互相覆盖。
    """

    def __init__(self, path: str | None = None) -> None:
        self.path: str = path or _DEFAULT_REC_PATH
        self._write_lock = threading.Lock()
        self._state: dict[str, object] = {
            "gun": "",
            "muzzle": 1,
            "grip": 1,
            "stock": 1,
            "scope": 1,
            "stance": "stand",
        }

    def write(
        self,
        gun: str | None = None,
        muzzle: int | None = None,
        grip: int | None = None,
        stock: int | None = None,
        scope: int | None = None,
        stance: str | None = None,
    ) -> None:
        """原子写入 rec.lua

        所有参数可选，传 None 表示沿用上一次写入的值。

        Args:
            gun: 枪械名称，如 "M416"，空字符串表示未识别
            muzzle: 枪口索引 (1=无, 2=补偿器, 3=消焰器, 4=消音器, 5=制退器)
            grip: 握把索引 (1=无, 2=垂直, 3=斜向, 4=拇指, 5=半截, 6=轻型)
            stock: 枪托索引 (1=无, 2=战术, 3=重型)
            scope: 倍镜 (1=红点/全息, 2=2倍, 3=3倍, 4=4倍, 6=6倍)
            stance: 姿态 stand / crouch / prone
        """
        updates = {
            "gun": gun,
            "muzzle": muzzle,
            "grip": grip,
            "stock": stock,
            "scope": scope,
            "stance": stance,
        }
        with self._write_lock:
            for key, value in updates.items():
                if value is not None:
                    self._state[key] = value
            self._flush()

    def update_stance(self, stance: str) -> None:
        """仅更新姿态字段，枪械/配件沿用上次写入的值"""
        self.write(stance=stance)

    def _flush(self) -> None:
        gun = str(self._state["gun"])
        content = (
            "-- auto-generated by pubg-gun-control, do not edit\n"
            f'rec_gun = "{gun}"\n'
            f"rec_muzzle = {self._state['muzzle']}\n"
            f"rec_grip = {self._state['grip']}\n"
            f"rec_stock = {self._state['stock']}\n"
            f"rec_scope = {self._state['scope']}\n"
            f'rec_stance = "{self._state["stance"]}"\n'
        )

        tmp_path = self.path + ".tmp"
        try:
            with open(tmp_path, "w", encoding="utf-8") as f:
                f.write(content)
            os.replace(tmp_path, self.path)
            logger.debug("rec.lua 已写入: gun=%s stance=%s", gun, self._state["stance"])
        except OSError as exc:
            logger.error("写入 rec.lua 失败: %s", exc)

    def get_path(self) -> str:
        """返回 rec.lua 的绝对路径"""
        return str(Path(self.path).resolve())
